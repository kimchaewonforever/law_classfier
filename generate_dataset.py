def fill(tpl: str) -> str:
    t, t2 = random.sample(TOPICS, 2)
    return (
        tpl.replace("{t2}", t2)
        .replace("{t}", t)
        .replace("{c}", case_no())
        .replace("{cn}", random.choice(COURT_NAMES))
        .replace("{s}", random.choice(SCENARIOS))
    )


def expand(templates, label, n):
    seen, rows = set(), []
    while len(rows) < n:
        q = fill(random.choice(templates))
        if q not in seen:
            seen.add(q)
            rows.append((q, label))
    return rows


def main():
    per_class = 500
    rows = (
        expand(LEGAL_TPL, "LEGAL", per_class)
        + expand(JUDGMENT_TPL, "JUDGMENT", per_class)
        + expand(MIXED_TPL, "MIXED", per_class)
        + HANDWRITTEN
    )
    random.shuffle(rows)

    os.makedirs("data", exist_ok=True)
    with open("data/dataset.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["text", "label"])
        w.writerows(rows)

    from collections import Counter

    print(f"總筆數: {len(rows)}")
    print(Counter(label for _, label in rows))


if __name__ == "__main__":
    main()
